// Compresses dist/ into ../include/web_assets.h for the firmware to serve.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";
import { gzipSync } from "node:zlib";

const MAX_FILE = 5488; // MAX_BODY in src/server.cpp
const MAX_TOTAL = 15 * 1024;

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript",
  ".css": "text/css",
};

const dist = join(import.meta.dirname, "../dist");
const output = join(import.meta.dirname, "../../include/web_assets.h");

const assets = readdirSync(dist, { recursive: true, withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => {
    const file = join(entry.parentPath, entry.name);
    const path = file.slice(dist.length).replaceAll("\\", "/");
    const type = TYPES[extname(file)];
    if (!type) throw new Error(`${path}: no content type for this extension`);
    const data = gzipSync(readFileSync(file), { level: 9 });
    data[9] = 0xff; // the gzip OS byte, so every platform generates the same file
    return { path: path === "/index.html" ? "/" : path, type, data, immutable: path !== "/index.html" };
  })
  .sort((a, b) => (a.path < b.path ? -1 : 1));

let total = 0;
for (const { path, data } of assets) {
  total += data.length;
  console.log(`${String(data.length).padStart(6)}  ${path}`);
}
console.log(`${String(total).padStart(6)}  total`);

const tooBig = assets.filter(({ data }) => data.length > MAX_FILE);
if (tooBig.length > 0) {
  throw new Error(`Over ${MAX_FILE} bytes, split further: ${tooBig.map(({ path }) => path).join(", ")}`);
}
if (total > MAX_TOTAL) throw new Error(`Total is over ${MAX_TOTAL} bytes`);

const arrays = assets.map(({ data }, i) => {
  const lines = [];
  for (let at = 0; at < data.length; at += 16) {
    lines.push("\t" + [...data.subarray(at, at + 16)].map((b) => `0x${b.toString(16).padStart(2, "0")},`).join(""));
  }
  return `const uint8_t ASSET_${i}[] = {\n${lines.join("\n")}\n};\n`;
});

const rows = assets.map(
  ({ path, type, immutable }, i) => `\t{"${path}", "${type}", ASSET_${i}, sizeof(ASSET_${i}), ${immutable}},`,
);

writeFileSync(
  output,
  `// Generated by web/scripts/embed.mjs. Do not edit; run "npm run build" in web/.
#pragma once

#include <stdint.h>

struct Asset
{
	const char *path;
	const char *contentType;
	const uint8_t *data; // gzip
	uint16_t length;
	bool immutable; // the name changes whenever the content does
};

${arrays.join("\n")}
const Asset ASSETS[] = {
${rows.join("\n")}
};
`,
);
